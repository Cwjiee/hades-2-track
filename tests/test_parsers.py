import struct
import unittest

from hades_track import luabins, sjson


def enc_string(text: str) -> bytes:
    raw = text.encode()
    return b"S" + struct.pack("<I", len(raw)) + raw


def enc_number(value: float) -> bytes:
    return b"N" + struct.pack("<d", value)


def enc_table(pairs) -> bytes:
    out = b"T" + struct.pack("<II", 0, len(pairs))
    for key, value in pairs:
        out += enc_string(key) + value
    return out


class LuabinsTest(unittest.TestCase):
    def test_roundtrip_nested(self):
        inner = enc_table([("God", enc_string("Apollo")), ("Rarity", enc_number(2))])
        blob = b"\x01" + enc_table([("Trait", inner), ("Boss", enc_string("Hecate"))])
        values = luabins.loads(blob)
        self.assertEqual(len(values), 1)
        table = values[0]
        self.assertEqual(table["Boss"], "Hecate")
        self.assertEqual(table["Trait"]["God"], "Apollo")
        self.assertEqual(table["Trait"]["Rarity"], 2.0)

    def test_primitives(self):
        blob = b"\x03" + b"-" + b"1" + enc_number(3.5)
        self.assertEqual(luabins.loads(blob), [None, True, 3.5])

    def test_truncated_raises(self):
        with self.assertRaises(luabins.LuaError):
            luabins.loads(b"\x01S\x08\x00\x00\x00ab")

    def test_trailing_bytes_raise(self):
        with self.assertRaises(luabins.LuaError):
            luabins.loads(b"\x01N" + struct.pack("<d", 1.0) + b"junk")


class SjsonTest(unittest.TestCase):
    SAMPLE = """
    {
      /* generated by the game */
      lang = "en"
      Texts = [
        { Id = "ApolloWeaponBoon" DisplayName = "Nova Strike" }
        { Id = "SolarRing" DisplayName = "Solar {#BoldFormat}Ring" Description = "line\\nbreak" }
      ]
      Nested = { A = 1 B = true C = false }
    }
    """

    def test_parses_arrays_and_tables(self):
        data = sjson.loads(self.SAMPLE)
        self.assertEqual(data["lang"], "en")
        self.assertEqual(len(data["Texts"]), 2)
        self.assertEqual(data["Texts"][1]["DisplayName"], "Solar {#BoldFormat}Ring")
        self.assertEqual(data["Texts"][1]["Description"], "line\nbreak")
        self.assertEqual(data["Nested"], {"A": 1, "B": True, "C": False})

    def test_comments_ignored(self):
        self.assertEqual(sjson.loads('{ A = 1 } // trailing')["A"], 1)


if __name__ == "__main__":
    unittest.main()
